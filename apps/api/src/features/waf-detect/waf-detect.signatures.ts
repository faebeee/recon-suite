/** Evidence per matching signature for one response. */
export function matchSignatures(view: ResponseView): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const sig of SIGNATURES) {
    const evidence: string[] = [];
    for (const [name, pattern] of sig.headers ?? []) {
      const value = view.headers[name];
      if (value === undefined) continue;
      if (!pattern) evidence.push(`${name} header`);
      else if (pattern.test(value))
        evidence.push(`${name}: ${value.slice(0, 80)}`);
    }
    for (const re of sig.cookies ?? []) {
      const hit = view.cookies.find((c) => re.test(c));
      if (hit) evidence.push(`${hit} cookie`);
    }
    for (const [re, label] of sig.body ?? []) {
      if (re.test(view.body)) evidence.push(label);
    }
    if (evidence.length) out.set(sig.name, evidence);
  }
  return out;
}

export function kindsOf(name: string): EdgeKind[] {
  return SIGNATURES.find((s) => s.name === name)?.kinds ?? [];
}

/** Cookie names of Set-Cookie headers. */
export function cookieNames(setCookies: string[]): string[] {
  return setCookies.map((c) => c.split('=')[0]?.trim() ?? '').filter(Boolean);
}

