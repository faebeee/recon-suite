import type { EdgeKind } from '@recon/shared';

/** What one response exposes to the matcher. */
export interface ResponseView {
  /** Lower-case header names. */
  headers: Record<string, string>;
  /** Cookie names from Set-Cookie. */
  cookies: string[];
  /** Body prefix. */
  body: string;
}

interface Signature {
  name: string;
  kinds: EdgeKind[];
  /** Header present (no pattern) or header value matching. */
  headers?: [string, RegExp?][];
  cookies?: RegExp[];
  /** Block page or error page text. */
  body?: [RegExp, string][];
}

